#!/usr/bin/env bash
# Packs Fogu-x86_64.AppImage from the glibc 2.28 build of scripts/package-linux.sh: the binary,
# the libraries of scripts/appimage-libs.sh with their licences, and assets/appimage/AppRun.
# Usage: scripts/package-appimage.sh [binary] [libdir]; downloads a pinned appimagetool.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
bin=${1:-target/compat/release/fogu}
libs=${2:-target/compat/appimage-lib}

app=$(mktemp -d)/Fogu.AppDir
tool=$(dirname "$app")/appimagetool
trap 'rm -rf "$(dirname "$app")"' EXIT
mkdir -p "$app/usr/bin" "$app/usr/lib" "$app/usr/share/doc/fogu/libraries"
cp "$bin" "$app/usr/bin/fogu"
cp "$libs"/*.so.* "$app/usr/lib/"
cp "$libs"/licenses/* "$app/usr/share/doc/fogu/libraries/"
# THIRD_PARTY_CRATES: generated by the release workflow (`cargo about generate`).
cp LICENSE THIRD_PARTY_LICENSES THIRD_PARTY_CRATES assets/fonts/*-LICENSE.txt \
    "$app/usr/share/doc/fogu/"
cp assets/fogu.desktop "$app/"
cp assets/icons/fogu-256.png "$app/fogu.png"
install -m755 assets/appimage/AppRun "$app/AppRun"

curl -fsSLo "$tool" https://github.com/AppImage/appimagetool/releases/download/1.9.1/appimagetool-x86_64.AppImage
echo "ed4ce84f0d9caff66f50bcca6ff6f35aae54ce8135408b3fa33abfc3cb384eb0  $tool" | sha256sum -c - >/dev/null
chmod +x "$tool"
APPIMAGE_EXTRACT_AND_RUN=1 ARCH=x86_64 "$tool" "$app" Fogu-x86_64.AppImage
